import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Builds the API into one self-contained file.
 *
 *   node scripts/build-function.mjs <outfile>
 *
 * Two things have to be inlined, and for the same reason: a serverless function
 * is a single file on a machine that has nothing else of ours on it.
 *
 * The workspace packages, because `@tapas/api`'s main is `src/index.ts` — raw
 * TypeScript, which suits tsx and vite and nothing else. A plain Node runtime
 * resolved that bare import to a file it could not load.
 *
 * And the migrations, because `runMigrations` reads a directory by default and
 * there is no directory: the `.sql` files are not in the deployment, and the
 * path the bundle would compute for them points at somewhere that does not
 * exist. Generating them as data means the function reads no files at all —
 * which also lets a second deployment, rooted somewhere else in this repo,
 * bundle the same entry without needing to reach outside its own tree.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = process.argv[2];
if (!outfile) {
  console.error('usage: node scripts/build-function.mjs <outfile>');
  process.exit(1);
}

/** The migrations, as a module the bundler can swallow. */
function writeMigrationsModule() {
  const dir = join(root, 'packages/api/migrations');
  const migrations = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((name) => ({ name, sql: readFileSync(join(dir, name), 'utf8') }));

  const generated = join(root, 'serverless/migrations.generated.ts');
  mkdirSync(dirname(generated), { recursive: true });
  writeFileSync(
    generated,
    `// Generated by scripts/build-function.mjs — do not edit.\n` +
      `// The .sql files, as data, so the bundled function reads no files.\n` +
      `import type { Migration } from '@tapas/api';\n\n` +
      `export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};\n`,
  );
  return migrations.length;
}

const count = writeMigrationsModule();

execFileSync(
  'npx',
  [
    'esbuild',
    join(root, 'serverless/entry.ts'),
    '--bundle',
    '--platform=node',
    '--format=esm',
    '--target=node22',
    `--outfile=${resolve(outfile)}`,
    '--external:pg-native',
    // A dependency calls `require`, which esbuild's ESM output refuses unless
    // the bundle carries one built from `createRequire`.
    `--banner:js=import{createRequire as ___cr}from'node:module';const require=___cr(import.meta.url);`,
    '--log-level=warning',
  ],
  { cwd: root, stdio: 'inherit' },
);

console.log(`bundled ${outfile} with ${count} migrations inlined`);
